export type ToolIconData = { path: string; hex: string; title: string } | null;

export function toolIcon(name: string): ToolIconData {
  const icon = MAP[name.trim().toLowerCase()];
  return icon ? { path: icon.path, hex: icon.hex, title: icon.title } : null;
}

/** Brand colours that are too dark to read on the ink background get lifted to cream. */
export function readableHex(hex: string): string {
  const n = parseInt(hex, 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  const lum = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
  return lum < 0.28 ? "#FFF8E7" : `#${hex}`;
}
